import {THEME_BOOTSTRAP} from '../src/lib/theme-bootstrap.ts';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {PUBLIC_PAGES, SITE_NAME, SITE_ORIGIN, HOME_DESCRIPTION, HOME_TITLE, WEBSITE_SCHEMA, WEBSITE_JSON_LD, SOCIAL_IMAGE, indexableBuild, robotsValue, renderSitemap, ROBOTS_TXT} from '../src/lib/seo.ts';
const root=new URL('../',import.meta.url);
const expected=process.argv.includes('--production')?true:process.argv.includes('--preview')?false:indexableBuild(process.env);
const escape=value=>value.replace(/[&<>"']/g,char=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[char]));
const config=JSON.parse(await readFile(new URL('vercel.json',root),'utf8'));
const csp=config.headers.flatMap(rule=>rule.headers).find(h=>h.key==='Content-Security-Policy').value;
const hash=createHash('sha256').update(WEBSITE_JSON_LD).digest('base64');
const themeHash=createHash('sha256').update(THEME_BOOTSTRAP).digest('base64');
assert.ok(csp.includes(`'sha256-${themeHash}'`),'CSP must permit exactly the pre-paint theme controller');
assert.ok(csp.includes(`'sha256-${hash}'`),'CSP must permit exactly the generated JSON-LD payload');
assert.ok(!csp.match(/script-src [^;]*'unsafe-inline'/),'Inline JavaScript must remain blocked');
assert.ok(config.headers.some(rule=>rule.missing?.some(c=>c.type==='host'&&c.value==='^branchquest\\.app$')&&rule.headers.some(h=>h.key==='X-Robots-Tag'&&h.value.includes('noindex'))),'Preview-host noindex header is required');
for(const page of Object.values(PUBLIC_PAGES)){
 const file=page.path==='/'?'index.html':page.path.slice(1)+'/index.html';
 const html=await readFile(new URL('dist/'+file,root),'utf8');
 assert.equal(html.match(/<script id="branchquest-theme">([\s\S]*?)<\/script>/)?.[1],THEME_BOOTSTRAP);
 assert.ok(html.indexOf('id="branchquest-theme"')<html.indexOf('rel="stylesheet"'),'Theme must resolve before linked styles and first paint');
 assert.match(html,/<html lang="he" dir="rtl">/);
 assert.ok(/<link[^>]*rel="stylesheet"/.test(html),'Initial HTML needs CSS before JavaScript');
 assert.ok(html.includes('data-initial-route="'+Object.entries(PUBLIC_PAGES).find(([,p])=>p===page)[0]+'"'),'Hydration route must match the pre-rendered document');
 assert.ok(!html.includes('class="seo-static-shell"'),'The generic landing shell must not return');
 assert.ok(html.includes(`<title>${escape(page.title)}</title>`),file+' title');
 assert.equal((html.match(/<title>/g)??[]).length,1);
 assert.ok(html.includes(`<meta name="description" content="${escape(page.description)}"`));
 assert.equal((html.match(/name="description"/g)??[]).length,1);
 assert.ok(html.includes(`<meta name="robots" content="${robotsValue(expected)}"`),file+' indexability');
 assert.ok(html.includes(`<link rel="canonical" href="${SITE_ORIGIN}${page.path}"`));
 assert.equal((html.match(/rel="canonical"/g)??[]).length,1);
 assert.ok(html.includes(`<meta property="og:site_name" content="${SITE_NAME}"`));
 assert.ok(html.includes(`<meta property="og:url" content="${SITE_ORIGIN}${page.path}"`));
 assert.ok(html.includes(`<meta property="og:image" content="${SOCIAL_IMAGE}"`));
 assert.ok(html.includes('name="twitter:card" content="summary_large_image"'));
 assert.ok(!html.includes('name="keywords"'));
 const ld=html.match(/<script type="application\/ld\+json" id="website-jsonld">([^]*?)<\/script>/);
 assert.ok(ld);assert.deepEqual(JSON.parse(ld[1]),WEBSITE_SCHEMA);
 assert.equal((html.match(/application\/ld\+json/g)??[]).length,1);
 assert.equal((html.match(/<h1[ >]/g)??[]).length,1);
 assert.ok(html.includes('is not affiliated with or endorsed by the Technion'));
 assert.ok(html.includes('href="/about"'));
 if(page.path==='/')assert.ok(html.includes('href="/feedback"'));
 assert.ok(html.includes('<!--seo:content:start-->')&&html.includes('<!--seo:content:end-->'));
 if(page.path==='/'){assert.ok(html.includes(HOME_DESCRIPTION));assert.ok(html.includes(HOME_TITLE));}
 if(page.path!=='/')assert.ok(config.rewrites.some(rule=>rule.source===page.path&&rule.destination==='/'+file));
}
assert.equal(await readFile(new URL('dist/sitemap.xml',root),'utf8'),renderSitemap());
assert.equal((renderSitemap().match(/<loc>/g)??[]).length,3);
assert.equal(await readFile(new URL('dist/robots.txt',root),'utf8'),ROBOTS_TXT);
const missing=await readFile(new URL('dist/404.html',root),'utf8');
assert.ok(missing.includes('name="robots" content="noindex,nofollow"'));
assert.ok(!missing.includes('type="module"'));assert.ok(!missing.includes('rel="canonical"'));
const image=await readFile(new URL('dist/og-image.png',root));
assert.equal(image.toString('hex',0,8),'89504e470d0a1a0a');assert.equal(image.readUInt32BE(16),1200);assert.equal(image.readUInt32BE(20),630);
assert.match(await readFile(new URL('dist/favicon.svg',root),'utf8'),/viewBox="0 0 40 40"/);
console.log(`SEO artifact checks passed: 3 public pages, ${expected?'production indexable':'preview/development noindex'}, sitemap, robots, JSON-LD/CSP, canonical/social metadata, 404 and sharing image.`);
